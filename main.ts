/**
 * The model's constants, as the dashboard states them. The formula is the whole model, and
 * every multiplier below is computed from the snapshot's own figures — TVL, seven-day growth,
 * how long the protocol has run, how many chains it runs on, and its category. No protocol
 * name is ever special-cased: the same function scores every row.
 */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  maturity_old_days: number;
  maturity_old_discount: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

