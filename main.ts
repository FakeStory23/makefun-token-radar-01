// Token Radar: a token launch radar in one Node program (Node 22, standard library only).
//
// It reads the sealed snapshot from /input/snapshot.json (or --input <file|dir>), scores every
// protocol that records no token with the model below, writes the ranked board to
// /output/board.json, and copies this repository's dashboard/ and screenshots/ to /output.
// Last, it writes /output/dossier.json, the summary the judge reads, with the vendored
// make.fun library (vendor/makefun-board.ts, the scorer's own copy, byte for byte).
//
// The dashboard is a static page, no framework and no network: dashboard/index.html,
// dashboard/app.css and dashboard/app.js read /output/data.js, which this program writes
// from the same board, so the page and the board can never disagree.
//
// Outside the grader's container, MAKEFUN_OUTPUT_DIR stands in for /output:
//   mkdir -p out && MAKEFUN_OUTPUT_DIR=out node main.ts --input ../input/snapshot.json
//
// The program is deterministic: two runs write byte-identical outputs. No clock, no random
// numbers; every sort has a total order (implied value, then slug) and every object is built
// in a fixed key order.

